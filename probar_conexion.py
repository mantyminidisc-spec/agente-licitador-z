fallas = [n for n, ok, _ in resultados if not ok]
print(f"  Pruebas: {len(resultados)} | Fallas: {len(fallas)}")
if fallas:
    print("  Puntos a corregir:")
    for f in fallas:
        print(f"   - {f}")
